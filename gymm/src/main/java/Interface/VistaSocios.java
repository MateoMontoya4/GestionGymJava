    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            controller.registrar(txtNombre.getText(), txtDni.getText(), txtTelefono.getText(),
                    txtEmail.getText(), (String) cbxAptMedico.getSelectedItem(), (String) cbxEstado.getSelectedItem());
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Socio registrado correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {
            controller.modificar(idSeleccionado(), txtNombre.getText(), txtDni.getText(), txtTelefono.getText(),
                    txtEmail.getText(), (String) cbxAptMedico.getSelectedItem(), (String) cbxEstado.getSelectedItem());
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Socio modificado correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int id = idSeleccionado();
        // Si no hay selección, el controlador avisa; solo se pide confirmación cuando hay algo para borrar.
        if (id > 0 && !Mensajes.confirmar(this, "¿Está seguro de eliminar al socio seleccionado?")) {
            return;
        }
        try {
            controller.eliminar(id);
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Socio eliminado correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    /** Vuelve a leer los socios de la base de datos y los muestra en la tabla. */
    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        try {
            for (Socio s : controller.listar()) {
                modeloTabla.addRow(new Object[]{s.getIdSocio(), s.getNombre(), s.getDni(), s.getTelefono(),
                    s.getEmail(), s.getAptMedico(), s.getEstadoMembresia()});
            }
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }

    /** Copia al formulario los datos de la fila elegida en la tabla. */
    private void cargarFilaSeleccionada() {
        int fila = tblSocios.getSelectedRow();
        if (fila < 0) {
            return;
        }
        txtIdSocio.setText(celda(fila, 0));
        txtNombre.setText(celda(fila, 1));
        txtDni.setText(celda(fila, 2));
        txtTelefono.setText(celda(fila, 3));
        txtEmail.setText(celda(fila, 4));
        cbxAptMedico.setSelectedItem(celda(fila, 5));
        cbxEstado.setSelectedItem(celda(fila, 6));
    }

    /** Devuelve el texto de una celda de la tabla ("" si es nula). */
    private String celda(int fila, int columna) {
        Object valor = modeloTabla.getValueAt(fila, columna);
        return valor == null ? "" : valor.toString();
    }

    /** Devuelve el id del socio elegido en la tabla, o 0 si no hay ninguno. */
    private int idSeleccionado() {
        String texto = txtIdSocio.getText().trim();
        return texto.isEmpty() ? 0 : Integer.parseInt(texto);
    }

    /** Deja el formulario vacío y sin fila elegida, listo para cargar un socio nuevo. */
    private void limpiarFormulario() {
        txtIdSocio.setText("");
        txtNombre.setText("");
        txtDni.setText("");
        txtTelefono.setText("");
        txtEmail.setText("");
        cbxAptMedico.setSelectedIndex(0);
        cbxEstado.setSelectedIndex(0);
        tblSocios.clearSelection();
    }

