    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            controller.registrar(txtNombreClase.getText(), txtCupos.getText(), txtHorarios.getText(),
                    txtProfesor.getText(), txtPrecio.getText());
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Actividad registrada correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {
            controller.modificar(idSeleccionado(), txtNombreClase.getText(), txtCupos.getText(),
                    txtHorarios.getText(), txtProfesor.getText(), txtPrecio.getText());
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Actividad modificada correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int id = idSeleccionado();
        // Si no hay selección, el controlador avisa; solo se pide confirmación cuando hay algo para borrar.
        if (id > 0 && !Mensajes.confirmar(this, "¿Está seguro de eliminar la actividad seleccionada?")) {
            return;
        }
        try {
            controller.eliminar(id);
            limpiarFormulario();
            cargarTabla();
            Mensajes.informar(this, "Actividad eliminada correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        limpiarFormulario();
    }//GEN-LAST:event_btnLimpiarActionPerformed

    /** Vuelve a leer las actividades de la base de datos y las muestra en la tabla. */
    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        try {
            for (Actividad a : controller.listar()) {
                modeloTabla.addRow(new Object[]{a.getIdActividad(), a.getNombreActividad(), a.getCupos(),
                    a.getHorarios(), a.getProfesor(), a.getPrecio()});
            }
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }

    /** Copia al formulario los datos de la fila elegida en la tabla. */
    private void cargarFilaSeleccionada() {
        int fila = tblActividades.getSelectedRow();
        if (fila < 0) {
            return;
        }
        txtIdActividad.setText(celda(fila, 0));
        txtNombreClase.setText(celda(fila, 1));
        txtCupos.setText(celda(fila, 2));
        txtHorarios.setText(celda(fila, 3));
        txtProfesor.setText(celda(fila, 4));
        txtPrecio.setText(celda(fila, 5));
    }

    /** Devuelve el texto de una celda de la tabla ("" si es nula). */
    private String celda(int fila, int columna) {
        Object valor = modeloTabla.getValueAt(fila, columna);
        return valor == null ? "" : valor.toString();
    }

    /** Devuelve el id de la actividad elegida en la tabla, o 0 si no hay ninguna. */
    private int idSeleccionado() {
        String texto = txtIdActividad.getText().trim();
        return texto.isEmpty() ? 0 : Integer.parseInt(texto);
    }

    /** Deja el formulario vacío y sin fila elegida, listo para cargar una actividad nueva. */
    private void limpiarFormulario() {
        txtIdActividad.setText("");
        txtNombreClase.setText("");
        txtCupos.setText("");
        txtHorarios.setText("");
        txtProfesor.setText("");
        txtPrecio.setText("");
        tblActividades.clearSelection();
    }

