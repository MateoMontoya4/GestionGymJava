    private void btnInscribirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInscribirActionPerformed
        try {
            controller.inscribir(idSocioElegido(), idActividadElegida());
            actualizarPantalla();
            Mensajes.informar(this, "Socio inscripto correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnInscribirActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {
            controller.modificar(idSeleccionado(), idSocioElegido(), idActividadElegida());
            actualizarPantalla();
            Mensajes.informar(this, "Inscripción modificada correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnDarDeBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDarDeBajaActionPerformed
        int id = idSeleccionado();
        // Si no hay selección, el controlador avisa; solo se pide confirmación cuando hay algo para borrar.
        if (id > 0 && !Mensajes.confirmar(this, "¿Está seguro de dar de baja la inscripción seleccionada?")) {
            return;
        }
        try {
            controller.darDeBaja(id);
            actualizarPantalla();
            Mensajes.informar(this, "Inscripción dada de baja correctamente.");
        } catch (GymException e) {
            Mensajes.mostrarError(this, e);
        }
    }//GEN-LAST:event_btnDarDeBajaActionPerformed

    /** Recarga combos y tabla, y deja el formulario vacío. */
    private void actualizarPantalla() {
        limpiarFormulario();
        cargarCombos();
        cargarTabla();
    }

    /** Llena las listas desplegables con los socios y actividades que hay en la base de datos. */
    private void cargarCombos() {
        try {
            socios = socioController.listar();
            actividades = actividadController.listar();
        } catch (GymException e) {
            socios = new ArrayList<>();
            actividades = new ArrayList<>();
            Mensajes.mostrarError(this, e);
        }
        DefaultComboBoxModel<String> modeloSocios = new DefaultComboBoxModel<>();
        for (Socio s : socios) {
            modeloSocios.addElement(s.getIdSocio() + " - " + s.getNombre() + " (DNI " + s.getDni() + ")");
        }
        cbxSocio.setModel(modeloSocios);
        DefaultComboBoxModel<String> modeloActividades = new DefaultComboBoxModel<>();
        for (Actividad a : actividades) {
            modeloActividades.addElement(a.getIdActividad() + " - " + a.getNombreActividad());
        }
        cbxActividad.setModel(modeloActividades);
        cbxSocio.setSelectedIndex(-1);
        cbxActividad.setSelectedIndex(-1);
    }

    /** Vuelve a leer las inscripciones de la base de datos y las muestra con el nombre del socio y de la actividad. */
    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        try {
            clases = controller.listar();
        } catch (GymException e) {
            clases = new ArrayList<>();
            Mensajes.mostrarError(this, e);
        }
        for (Clase c : clases) {
            modeloTabla.addRow(new Object[]{c.getIdClase(), nombreSocio(c.getIdSocio()), nombreActividad(c.getIdActividad())});
        }
    }

    /** Copia al formulario los datos de la inscripción elegida en la tabla. */
    private void cargarFilaSeleccionada() {
        int fila = tblClases.getSelectedRow();
        if (fila < 0 || fila >= clases.size()) {
            return;
        }
        Clase c = clases.get(fila);
        txtIdClase.setText(String.valueOf(c.getIdClase()));
        cbxSocio.setSelectedIndex(posicionSocio(c.getIdSocio()));
        cbxActividad.setSelectedIndex(posicionActividad(c.getIdActividad()));
    }

    private String nombreSocio(int idSocio) {
        int pos = posicionSocio(idSocio);
        return pos < 0 ? "(socio " + idSocio + ")" : socios.get(pos).getNombre();
    }

    private String nombreActividad(int idActividad) {
        int pos = posicionActividad(idActividad);
        return pos < 0 ? "(actividad " + idActividad + ")" : actividades.get(pos).getNombreActividad();
    }

    private int posicionSocio(int idSocio) {
        for (int i = 0; i < socios.size(); i++) {
            if (socios.get(i).getIdSocio() == idSocio) {
                return i;
            }
        }
        return -1;
    }

    private int posicionActividad(int idActividad) {
        for (int i = 0; i < actividades.size(); i++) {
            if (actividades.get(i).getIdActividad() == idActividad) {
                return i;
            }
        }
        return -1;
    }

    /** Devuelve el id del socio elegido en la lista, o 0 si no hay ninguno. */
    private int idSocioElegido() {
        int pos = cbxSocio.getSelectedIndex();
        return pos < 0 ? 0 : socios.get(pos).getIdSocio();
    }

    /** Devuelve el id de la actividad elegida en la lista, o 0 si no hay ninguna. */
    private int idActividadElegida() {
        int pos = cbxActividad.getSelectedIndex();
        return pos < 0 ? 0 : actividades.get(pos).getIdActividad();
    }

    /** Devuelve el id de la inscripción elegida en la tabla, o 0 si no hay ninguna. */
    private int idSeleccionado() {
        String texto = txtIdClase.getText().trim();
        return texto.isEmpty() ? 0 : Integer.parseInt(texto);
    }

    /** Deja el formulario vacío y sin fila elegida. */
    private void limpiarFormulario() {
        txtIdClase.setText("");
        cbxSocio.setSelectedIndex(-1);
        cbxActividad.setSelectedIndex(-1);
        tblClases.clearSelection();
    }

